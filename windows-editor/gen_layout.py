"""Turns a plugin's ui.json into af_layout.h for the Windows editor (see af_editor_win.h).

    python gen_layout.py <ui.json> <plugin name> <out dir>

ui.json widgets map to: knob -> Knob, fader -> Fader, switch -> Switch, slider (menu overlay) -> Menu.
"empty" slots stay empty. Parameter names are looked up in the plugin at run time.
"""
import json
import os
import sys

# One accent colour per plugin, spread around the colour wheel so that two windows open side by side
# are told apart at a glance. Arpeggio keeps the cyan of its first version.
ACCENTS = {
    "Arpeggio":    "#00C8FF",  # cyan
    "Bassline":    "#FF5A4F",  # red
    "Percbox":     "#FF7A2F",  # orange
    "Drumbox":     "#FFB020",  # amber
    "Brassline":   "#F0D030",  # brass yellow
    "Chordbox":    "#A3D93F",  # lime
    "Chimes":      "#5BE07A",  # green
    "Padscape":    "#3DDBB5",  # teal
    "Dronescape":  "#4F8CFF",  # blue
    "Digiwave":    "#7B6CFF",  # indigo
    "Impactor":    "#B04CFF",  # purple
    "Chorale":     "#E060F0",  # magenta
    "Leadline":    "#FF4FA3",  # pink
    "Warbox":      "#8A96A6",  # steel grey
    "Stringscape": "#D9B38C",  # sand
}

WIDGETS = {"knob": "Knob", "fader": "Fader", "switch": "Switch", "slider": "Menu"}


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(ui_json, name, out_dir, accent=None):
    with open(ui_json, encoding="utf-8") as fh:
        ui = json.load(fh)
    pages = []
    for page in ui["pages"]:
        controls = []
        for c in page["controls"]:
            if c == "empty":
                controls.append("{nullptr, afgui::Widget::Knob, false}")
                continue
            w = WIDGETS.get(c.get("widget", "knob"), "Knob")
            bipolar = "true" if c.get("polarity") == "bipolar" else "false"
            controls.append("{%s, afgui::Widget::%s, %s}" % (cstr(c["param"]), w, bipolar))
        pages.append("{%s, {\n            %s}}" % (cstr(page["name"]), ",\n            ".join(controls)))
    text = (
        "// Generated by gen_layout.py from ui.json. Do not edit.\n"
        "#pragma once\n"
        "inline const afgui::Layout& af_layout()\n"
        "{\n"
        "    static const afgui::Layout layout{%s, %s, {\n        %s}};\n"
        "    return layout;\n"
        "}\n" % (cstr(name), cstr(accent or ACCENTS.get(name) or ui.get("kit", "cyan")), ",\n        ".join(pages))
    )
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "af_layout.h")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return path


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    print(generate(sys.argv[1], sys.argv[2], sys.argv[3]))
